"""Generate src/textnorm_tables.inc and src/util_tables.inc from the installed arbtok.

The rules of arbtok.textnorm and arbtok.util read module-level patterns, strings and
tables. The port takes each one from the module itself, as the module holds it after
import, so that a pattern is byte for byte the one Python compiles. A name that is
defined twice, as _MONTH_NAMES is, has the value the second definition gives, which is
the value the functions read when they run.

A str becomes a u32string_view, a compiled pattern an Re with its pattern and flags, a
tuple of str an array, a frozenset of str a sorted array, a dict an array of pairs in
insertion order, and a str.maketrans table an array of Tr. Other values are written in
the port by hand. PATTERNS lists the compiled patterns by their Python names.

Usage: python -I tools/gen_textnorm_tables.py src
"""
import re
import sys
import unicodedata
from pathlib import Path

import arbtok
import arbtok.textnorm
import arbtok.util

SAFE_CATEGORIES = ("L", "N", "P", "S")


def literal(text: str) -> str:
    out = []
    for c in text:
        cp = ord(c)
        if c in '\\"':
            out.append("\\" + c)
        elif 0x20 <= cp < 0x7F:
            out.append(c)
        elif cp < 0xA0:
            out.append(f"\\{cp:03o}")
        elif unicodedata.category(c)[0] in SAFE_CATEGORIES and unicodedata.combining(c) == 0:
            out.append(c)
        else:
            out.append(f"\\U{cp:08X}")
    return 'U"' + "".join(out) + '"'


def emit(module, namespace: str) -> str:
    lines = [f"// Generated by tools/gen_textnorm_tables.py from {module.__name__} {arbtok.__version__}"
             " as imported; do not edit.", f"namespace {namespace} {{", ""]
    seen = {}
    count = 0
    for name, value in vars(module).items():
        if name.startswith("__"):
            continue
        cname = name.lstrip("_")
        body = None
        if isinstance(value, str):
            body = f"inline constexpr std::u32string_view {cname} = {literal(value)};"
        elif isinstance(value, re.Pattern):
            body = f"inline constexpr Re {cname} = {{{literal(value.pattern)}, {int(value.flags & ~re.UNICODE)}}};"
        elif isinstance(value, (tuple, frozenset)) and value and all(isinstance(v, str) for v in value):
            items = sorted(value) if isinstance(value, frozenset) else value
            body = (f"inline constexpr std::u32string_view {cname}[] = {{"
                    + ", ".join(literal(v) for v in items) + "};")
        elif isinstance(value, dict) and value and all(isinstance(k, str) for k in value):
            if all(isinstance(v, str) for v in value.values()):
                body = (f"inline constexpr std::pair<std::u32string_view, std::u32string_view> {cname}[] = {{"
                        + ", ".join(f"{{{literal(k)}, {literal(v)}}}" for k, v in value.items()) + "};")
            elif all(v is None or (isinstance(v, int) and not isinstance(v, bool) and v >= 0)
                     for v in value.values()):
                # -1 stands for None
                body = (f"inline constexpr std::pair<std::u32string_view, long long> {cname}[] = {{"
                        + ", ".join(f"{{{literal(k)}, {-1 if v is None else v}}}" for k, v in value.items()) + "};")
            elif all(isinstance(v, dict) and all(isinstance(a, str) and isinstance(b, str) for a, b in v.items())
                     for v in value.values()):
                # a dict of dicts by language: one array per language and a LangTable for each
                parts = []
                for lang, table in value.items():
                    entries = ", ".join(f"{{{literal(k)}, {literal(v)}}}" for k, v in table.items())
                    parts.append(f"inline constexpr std::pair<std::u32string_view, std::u32string_view> "
                                 f"{cname}_{lang.replace('-', '_')}[] = {{{entries}}};")
                parts.append(f"inline constexpr LangTable {cname}[] = {{"
                             + ", ".join(f"{{{literal(lang)}, {cname}_{lang.replace('-', '_')}, {len(t)}}}"
                                         for lang, t in value.items()) + "};")
                body = "\n".join(parts)
        elif isinstance(value, dict) and value and all(isinstance(k, int) for k in value):
            def target(v):
                if v is None:
                    return 'U"", false'
                return f"{literal(chr(v) if isinstance(v, int) else v)}, true"
            body = (f"inline constexpr Tr {cname}[] = {{"
                    + ", ".join(f"{{{k}, {target(v)}}}" for k, v in value.items()) + "};")
        elif isinstance(value, dict) and value and all(isinstance(k, tuple) and len(k) == 2 for k in value):
            body = (f"inline constexpr Pair2 {cname}[] = {{"
                    + ", ".join(f"{{{literal(a)}, {literal(b)}, {literal(v)}}}" for (a, b), v in value.items())
                    + "};")
        elif isinstance(value, int) and not isinstance(value, bool):
            body = f"inline constexpr long long {cname} = {value};"
        elif isinstance(value, range):
            body = f"inline constexpr Range {cname} = {{{value.start}, {value.stop}}};"
        if body is None:
            continue
        if cname in seen:
            raise SystemExit(f"{name} and {seen[cname]} have one C++ name")
        seen[cname] = name
        lines.append(body)
        count += 1
    patterns = [(n, seen_name) for seen_name, n in seen.items() if isinstance(vars(module)[n], re.Pattern)]
    lines.append("// Every compiled pattern by its Python name.")
    lines.append("inline constexpr NamedRe PATTERNS[] = {"
                 + ", ".join(f'{{"{n}", &{c}}}' for n, c in patterns) + "};")
    lines += ["", f"}}  // namespace {namespace}", ""]
    print(f"{module.__name__}: {count} definitions", file=sys.stderr)
    return "\n".join(lines)


def main():
    out = Path(sys.argv[1])
    (out / "textnorm_tables.inc").write_text(emit(arbtok.textnorm, "arbtok::textnorm::py"), encoding="utf-8")
    (out / "util_tables.inc").write_text(emit(arbtok.util, "arbtok::textnorm::py_util"), encoding="utf-8")


if __name__ == "__main__":
    main()
