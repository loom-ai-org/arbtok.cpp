"""Write src/ensemble/unicode_tables.inc from the reference interpreter.

The ensemble port needs the general category of a code point and the
canonical decompositions and compositions of NFD and NFC. These tables come
from the unicodedata module of the interpreter that runs the reference
package, so the port follows its Unicode version and not the one of the
system ICU.

Usage: python tools/goldens/ensemble_unicode.py src/ensemble/unicode_tables.inc \
           [--golden tests/goldens/ensemble_unicode.jsonl.gz]

--golden also writes the Unicode goldens: the category and combining class of
every code point, and NFD and NFC of every code point that they change, of
every Hangul syllable, and of a seeded set of random mark sequences.
"""

import gzip
import json
import random
import sys
import unicodedata

CATEGORIES = [
    "Cn", "Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No",
    "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Zs",
    "Zl", "Zp", "Cc", "Cf", "Cs", "Co",
]
MAX_CP = 0x10FFFF
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def runs(values):
    out = []
    start, prev = 0, values[0]
    for cp in range(1, len(values)):
        if values[cp] != prev:
            out.append((start, cp - 1, prev))
            start, prev = cp, values[cp]
    out.append((start, len(values) - 1, prev))
    return out


def main(path):
    cats = [CATEGORIES.index(unicodedata.category(chr(cp))) for cp in range(MAX_CP + 1)]
    cat_runs = runs(cats)
    ccc_runs = [r for r in runs([unicodedata.combining(chr(cp)) for cp in range(MAX_CP + 1)]) if r[2]]

    # Full canonical decompositions. Hangul syllables decompose by arithmetic in
    # the C++ code, as in CPython.
    decomp = []
    for cp in range(MAX_CP + 1):
        if HANGUL_FIRST <= cp <= HANGUL_LAST or 0xD800 <= cp <= 0xDFFF:
            continue
        d = unicodedata.normalize("NFD", chr(cp))
        if d != chr(cp):
            decomp.append((cp, [ord(c) for c in d]))

    # Primary composites: a two-code-point canonical mapping that NFC
    # recomposes. Singletons, non-starter decompositions and the composition
    # exclusions fail the round trip and drop out.
    comp = []
    for cp in range(MAX_CP + 1):
        if HANGUL_FIRST <= cp <= HANGUL_LAST or 0xD800 <= cp <= 0xDFFF:
            continue
        raw = unicodedata.decomposition(chr(cp))
        if not raw or raw.startswith("<"):
            continue
        parts = [int(x, 16) for x in raw.split()]
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
            comp.append((parts[0], parts[1], cp))
    comp.sort()

    pool = []
    rows = []
    for cp, seq in decomp:
        rows.append((cp, len(pool), len(seq)))
        pool.extend(seq)

    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"// Generated by tools/goldens/ensemble_unicode.py from Python "
                f"{sys.version.split()[0]} unicodedata {unicodedata.unidata_version}. Do not edit.\n")
        f.write(f'#define ARBTOK_ENSEMBLE_UNIDATA_VERSION "{unicodedata.unidata_version}"\n')
        f.write("static const CategoryRun kCategoryRuns[] = {\n")
        for a, b, c in cat_runs:
            f.write(f"{{0x{a:X},0x{b:X},{c}}},\n")
        f.write("};\n")
        f.write("static const CccRun kCccRuns[] = {\n")
        for a, b, c in ccc_runs:
            f.write(f"{{0x{a:X},0x{b:X},{c}}},\n")
        f.write("};\n")
        f.write("static const char32_t kDecompPool[] = {\n")
        for i in range(0, len(pool), 12):
            f.write(",".join(f"0x{x:X}" for x in pool[i:i + 12]) + ",\n")
        f.write("};\n")
        f.write("static const Decomposition kDecompositions[] = {\n")
        for cp, off, n in rows:
            f.write(f"{{0x{cp:X},{off},{n}}},\n")
        f.write("};\n")
        f.write("static const Composition kCompositions[] = {\n")
        for a, b, c in comp:
            f.write(f"{{0x{a:X},0x{b:X},0x{c:X}}},\n")
        f.write("};\n")
    print(f"category runs {len(cat_runs)}, ccc runs {len(ccc_runs)}, "
          f"decompositions {len(rows)}, compositions {len(comp)}", file=sys.stderr)


def golden(path):
    cps = [cp for cp in range(MAX_CP + 1) if not 0xD800 <= cp <= 0xDFFF]
    categories = "".join(unicodedata.category(chr(cp)) if not 0xD800 <= cp <= 0xDFFF else "Cs"
                         for cp in range(MAX_CP + 1))
    combining = "".join(f"{unicodedata.combining(chr(cp)):02x}" for cp in range(MAX_CP + 1))
    texts = []
    for cp in cps:
        c = chr(cp)
        if (unicodedata.normalize("NFD", c) != c or unicodedata.normalize("NFC", c) != c
                or unicodedata.combining(c)):
            texts.append(c)
    marks = [chr(cp) for cp in cps if unicodedata.combining(chr(cp))]
    composable = sorted({c for t in texts for c in unicodedata.normalize("NFD", t)})
    jamo = [chr(c) for c in list(range(0x1100, 0x1113)) + list(range(0x1161, 0x1176)) + list(range(0x11A8, 0x11C3))]
    rng = random.Random(15)
    for _ in range(30000):
        n = rng.randint(1, 8)
        parts = []
        for _ in range(n):
            r = rng.random()
            pool = marks if r < 0.35 else composable if r < 0.75 else jamo if r < 0.9 else texts
            parts.append(rng.choice(pool))
        texts.append("".join(parts))
    with gzip.open(path, "wt", encoding="utf-8", compresslevel=9) as f:
        f.write(json.dumps({"kind": "unicode-header", "unidata": unicodedata.unidata_version,
                            "python": sys.version.split()[0], "records": len(texts) + 1}) + "\n")
        f.write(json.dumps({"categories": categories, "combining": combining}) + "\n")
        for t in texts:
            f.write(json.dumps({"text": t, "nfd": unicodedata.normalize("NFD", t),
                                "nfc": unicodedata.normalize("NFC", t)}, ensure_ascii=False) + "\n")
    print(f"{path}: N in {len(texts) + 1}, N out {len(texts) + 1}", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
    if len(sys.argv) == 4 and sys.argv[2] == "--golden":
        golden(sys.argv[3])
