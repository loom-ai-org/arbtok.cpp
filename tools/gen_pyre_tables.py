"""Generate src/pyre_tables.inc from the running Python's re module and Unicode database.

src/pyre.cpp matches as Python's re does for str patterns: \\d is str.isdecimal(), \\w is
str.isalnum() or "_", and IGNORECASE compares the lowercase that _sre.unicode_tolower gives,
with the extra case pairs of re._casefix. src/textnorm_detail.cpp needs str.isupper(), str.islower(),
str.isdecimal() and str.isprintable(). The tables are taken from Python itself, so the two
agree on the same Unicode version; the version is written into the generated file.

Usage: python -I tools/gen_pyre_tables.py > src/pyre_tables.inc
"""
import _sre
import re._casefix
import sys
import unicodedata

MAX = 0x110000


def ranges(predicate):
    out, start = [], None
    for cp in range(MAX + 1):
        hit = cp < MAX and not 0xD800 <= cp <= 0xDFFF and predicate(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit_ranges(name, rows):
    print(f"static const char32_t {name}[{len(rows)}][2] = {{")
    for lo, hi in rows:
        print(f"  {{0x{lo:X}, 0x{hi:X}}},")
    print("};")


def main():
    print("// Generated by tools/gen_pyre_tables.py; do not edit.")
    print(f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.")
    emit_ranges("kDecimal", ranges(lambda cp: chr(cp).isdecimal()))
    emit_ranges("kUpper", ranges(lambda cp: chr(cp).isupper()))
    emit_ranges("kLowerCase", ranges(lambda cp: chr(cp).islower()))
    emit_ranges("kTitle", ranges(lambda cp: chr(cp).istitle() and not chr(cp).isupper()))
    emit_ranges("kPrintable", ranges(lambda cp: chr(cp).isprintable()))
    emit_ranges("kNumeric", ranges(lambda cp: chr(cp).isnumeric()))
    emit_ranges("kIsCased", ranges(lambda cp: _sre.unicode_iscased(cp)))
    lower = [(cp, _sre.unicode_tolower(cp)) for cp in range(MAX) if not 0xD800 <= cp <= 0xDFFF
             and _sre.unicode_tolower(cp) != cp]
    print(f"static const char32_t kSimpleLower[{len(lower)}][2] = {{")
    for cp, lo in lower:
        print(f"  {{0x{cp:X}, 0x{lo:X}}},")
    print("};")
    extra = sorted(re._casefix._EXTRA_CASES.items())
    width = max(len(v) for _, v in extra)
    print(f"struct ExtraCase {{ char32_t lo; unsigned char n; char32_t others[{width}]; }};")
    print(f"static const ExtraCase kExtraCases[{len(extra)}] = {{")
    for lo, others in extra:
        cells = ", ".join(f"0x{o:X}" for o in others) or "0"
        print(f"  {{0x{lo:X}, {len(others)}, {{{cells}}}}},")
    print("};")


if __name__ == "__main__":
    main()
